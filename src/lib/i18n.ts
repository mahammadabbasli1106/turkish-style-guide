// Get saved language or detect from browser
const SUPPORTED = ['en','tr','de','ru','az','ar','fr','it'];
const savedLanguage = typeof window !== 'undefined' ? localStorage.getItem('language') : null;
const browserLanguage = typeof navigator !== 'undefined' ? navigator.language.split('-')[0] : 'en';
const defaultLanguage = (savedLanguage && SUPPORTED.includes(savedLanguage))
  ? savedLanguage
  : (SUPPORTED.includes(browserLanguage) ? browserLanguage : 'en');

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: defaultLanguage,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false
    }
  });

// Sync <html> lang + dir (RTL for Arabic) on init and on every language change
function applyHtmlLangDir(lng: string) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lng;
  document.documentElement.dir = lng === 'ar' ? 'rtl' : 'ltr';
}
applyHtmlLangDir(defaultLanguage);
i18n.on('languageChanged', applyHtmlLangDir);

export default i18n;
